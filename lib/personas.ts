export const PERSONA_IDS = ["grandpa", "sister", "brother"] as const;
export type PersonaId = (typeof PERSONA_IDS)[number];

export const MODES = ["consult", "talk"] as const;
/** consult: 相談者から話す / talk: 相談相手のほうから話しかける */
export type Mode = (typeof MODES)[number];

export type TimeOfDay = "morning" | "day" | "evening" | "night";

export function timeOfDay(hour: number): TimeOfDay {
  if (hour >= 5 && hour < 11) return "morning";
  if (hour >= 11 && hour < 17) return "day";
  if (hour >= 17 && hour < 22) return "evening";
  return "night";
}

export type Persona = {
  id: PersonaId;
  name: string;
  role: string;
  tagline: string;
  greeting: string;
  placeholder: string;
  /** 話しかけモードの最初の一言は「時間帯のあいさつ」＋「その日の話題」で作る */
  hello: Record<TimeOfDay, string>;
  topics: string[];
};

/** 端末の日付で数えた通し日数。日付が変わると 1 増える */
function dayNumber(date: Date): number {
  return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
}

/**
 * 話しかけモードの最初の一言。話題は日付で決まるので、同じ日は同じ話題、翌日は必ず別の話題になる。
 * 相談相手ごとに順番をずらし、同じ日に3人が同じ趣旨の話題にならないようにしている。
 * skip を増やすと、その日の話題から順に次の話題へ進む（「別の話題にする」用）。
 */
export function opener(persona: Persona, now: Date, skip = 0): string {
  const offset = PERSONA_IDS.indexOf(persona.id) * 5;
  const topic = persona.topics[(dayNumber(now) + offset + skip) % persona.topics.length];
  return `${persona.hello[timeOfDay(now.getHours())]}${topic}`;
}

